export function t(locale: Locale, key: keyof (typeof UI_STRINGS)['es-AR']): string {
  return UI_STRINGS[locale][key] ?? UI_STRINGS['es-AR'][key];
}

export function detectInitialLocale(): Locale {
  if (typeof window === 'undefined') return 'es-AR';
  const path = window.location.pathname.toLowerCase();
  if (path.startsWith('/en-us')) return 'en-US';
  if (path.startsWith('/es-ar')) return 'es-AR';
  const stored = window.localStorage.getItem('mundoki_locale');
  if (stored === 'en-US' || stored === 'es-AR') return stored;
  const navLang = (navigator.language || '').toLowerCase();
  if (navLang.startsWith('en')) return 'en-US';
  return 'es-AR';
}
